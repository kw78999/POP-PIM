"""Generate vs_mass_threshold ROMs (vs_tables.svh) and the matching constants for the software reference.

Fixed point: per-token increment  inc = (T1[f>>8] * T2[f&255]) >> 16  ~= e^{(f/2^16)/8} * 2^16 (rounded down)
Bin weight:  E[b] = fp32(e^{(b-255)/8})            b = 1..255 (bin 0 is the clipped tail)
Tail bound:  E0P  = fp32_up(2^16 * e^{-254/8})     (upper bound of one tail token, in increment units)
Threshold:   KD(delta) = fp32_up((1-delta) * (1+2^-13)^2)   (covers 3-ulp table truncation and FP32 scan rounding)
"""
import json, math, sys
from pathlib import Path
import numpy as np
HERE = Path(__file__).resolve().parent


def f32_up(x):
    f = np.float32(x)
    return f if float(f) >= x else np.nextafter(f, np.float32(np.inf))


def tables():
    T1 = [math.floor(math.exp(i / 2048) * 65536) for i in range(256)]
    T2 = [math.floor(math.exp(i / 2 ** 19) * 65536) for i in range(256)]
    E = [float(np.float32(math.exp((b - 255) / 8))) for b in range(256)]
    E[0] = 0.0
    E0P = float(f32_up(65536 * math.exp(-254 / 8)))
    KD = {str(d): float(f32_up((1 - d) * (1 + 2 ** -13) ** 2)) for d in (0.002, 0.005, 0.01)}
    return dict(T1=T1, T2=T2, E=E, E0P=E0P, KD=KD)


def bits(x): return int(np.float32(x).view(np.uint32))


def main():
    t = tables()
    lines = ['// generated by gen_vs_tables.py; do not edit']
    for name, vals, w in (('vs_t1', t['T1'], 17), ('vs_t2', t['T2'], 17)):
        lines.append(f'function automatic [{w - 1}:0] {name}(input [7:0] i); case(i)')
        lines += [f' 8\'d{i}: {name}={w}\'d{v};' for i, v in enumerate(vals)]
        lines.append(f' default: {name}=0; endcase endfunction')
    lines.append("function automatic [31:0] vs_eb(input [7:0] b); case(b)")
    lines += [f" 8'd{b}: vs_eb=32'h{bits(v):08x};" for b, v in enumerate(t['E'])]
    lines.append(" default: vs_eb=0; endcase endfunction")
    (HERE / 'vs_tables.svh').write_text('\n'.join(lines) + '\n')
    (HERE / 'vs_tables.json').write_text(json.dumps(t))
    print('E0P', hex(bits(t['E0P'])), {k: hex(bits(v)) for k, v in t['KD'].items()})


if __name__ == '__main__':
    main()
